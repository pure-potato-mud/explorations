typedef struct code code;
struct code {
	uint8_t code;
	uint8_t value;
};

void swap(code** first, code** last) {
	code* temp = *first;
	*first = *last;
	*last = temp;
}

int16_t partition(code** list, int16_t firstIndex, int16_t lastIndex, int16_t pivotIndex) {
	uint8_t pivotValue = list[pivotIndex]->value;
	swap(list+pivotIndex, list+lastIndex);
	int16_t storeIndex = firstIndex;
	for (uint8_t i = firstIndex; i < lastIndex; i++) {
//		std::cout << +list[i]->value << " ";
		if (list[i]->value < pivotValue) {
			swap(list+storeIndex, list+i);
			++storeIndex;
		}
	}
	swap(list+lastIndex, list+storeIndex);
	return storeIndex;
}

