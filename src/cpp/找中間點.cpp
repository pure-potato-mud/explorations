#include<stdio.h>
using namespace std;
int main() {
	/*
	- 定義域 -
	高位範圍 0x81~0xfE
	低位範圍 0x40~0x7E,	0xA1 ~ 0xFE 
	
	- 有字的範圍 - 
	0xA140	到	0xA3BF	中間值	0xA26E或 0xA26F
	0xA440	到	0xA67E	中間值	0xB55F
	0xC940	到	0xF9DC	中間值	0xE17D
	*/
//	int A = 0xA140, B = 0xA3BF;
	int A = 0xA440, B = 0xC67E;
//	int A = 0xC940, B = 0xF9DC;
	int a = A, b = B;
	while (A != B && A+1 != B && B>=a && A<=b ) {
		A+=1; B-=1;
		if (A%0x100 == 0x7F) A+=0x22;
		if (A%0x100 == 0xFF) A+=0x41;
		if (B%0x100 == 0xA0) B-=0x22;
		if (B%0x100 == 0x3F) B-=0x41;
		printf("%X %X, %X\n",A,B,B-A);
	}
	printf("%X %X\n",A,B);
	
}
